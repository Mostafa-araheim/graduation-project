
    create table brand (
        brand_id integer generated by default as identity,
        brand_image varchar(255),
        brand_name varchar(255),
        primary key (brand_id)
    );

    create table cart (
        cart_id integer generated by default as identity,
        customer_id integer,
        pharmacy_id integer,
        total_price float4,
        created_at timestamp(6),
        primary key (cart_id)
    );

    create table cart_item (
        cart_id integer,
        cart_item_id integer generated by default as identity,
        medicine_id integer,
        price float4,
        quantity integer,
        primary key (cart_item_id)
    );

    create table category (
        category_id integer generated by default as identity,
        category_name varchar(255),
        image_url varchar(255),
        primary key (category_id)
    );

    create table inventory (
        inventory_id integer generated by default as identity,
        pharmacy_id integer unique,
        primary key (inventory_id)
    );

    create table inventory_record (
        expiry_date date not null,
        inventory_id integer not null,
        medicine_id integer not null,
        quantity integer,
        availability_status varchar(255),
        primary key (expiry_date, inventory_id, medicine_id)
    );

    create table invoice (
        invoice_id integer generated by default as identity,
        order_id integer unique,
        created_at timestamp(6),
        invoice_url varchar(255),
        primary key (invoice_id)
    );

    create table medication_reminder (
        customer_id integer,
        dosage_time time(0),
        notify_before_minutes integer,
        reminder_id integer generated by default as identity,
        medicine_name varchar(255),
        primary key (reminder_id)
    );

    create table medicine (
        brand_id integer,
        category_id integer,
        medicine_id integer generated by default as identity,
        requires_prescription boolean not null,
        description varchar(255),
        dosage_form varchar(255),
        manufacturer varchar(255),
        name varchar(255),
        strength varchar(255),
        primary key (medicine_id)
    );

    create table notification (
        is_read boolean not null,
        notification_id integer generated by default as identity,
        user_id integer,
        created_at timestamp(6),
        message varchar(255),
        type varchar(255),
        primary key (notification_id)
    );

    create table order_item (
        medicine_id integer,
        order_id integer,
        order_item_id integer generated by default as identity,
        price float4,
        quantity integer,
        primary key (order_item_id)
    );

    create table orders (
        customer_id integer,
        order_id integer generated by default as identity,
        pharmacy_id integer,
        total_amount float4,
        created_at timestamp(6),
        delivery_type varchar(255),
        payment_method varchar(255),
        status varchar(255),
        primary key (order_id)
    );

    create table p2p_listing (
        expiry_date date,
        listing_id integer generated by default as identity,
        price float4,
        quantity integer,
        seller_id integer,
        created_at timestamp(6),
        image_url varchar(255),
        medicine_name varchar(255),
        status varchar(255),
        primary key (listing_id)
    );

    create table p2p_transaction (
        buyer_id integer,
        listing_id integer unique,
        transaction_id integer generated by default as identity,
        created_at timestamp(6),
        status varchar(255),
        primary key (transaction_id)
    );

    create table pharmacy (
        owner_id integer,
        pharmacy_id integer generated by default as identity,
        total_rating float4,
        created_at timestamp(6),
        image_url varchar(255),
        name varchar(255),
        primary key (pharmacy_id)
    );

    create table pharmacy_address (
        pharmacy_id integer not null,
        apartment_number varchar(255),
        city varchar(255),
        country varchar(255),
        postal_code varchar(255),
        street varchar(255),
        primary key (pharmacy_id)
    );

    create table pharmacy_owner (
        owner_id integer generated by default as identity,
        user_id integer unique,
        primary key (owner_id)
    );

    create table pharmacy_review (
        customer_id integer,
        pharmacy_id integer,
        rating integer,
        review_id integer generated by default as identity,
        created_at timestamp(6),
        comment varchar(255),
        primary key (review_id)
    );

    create table prescription (
        customer_id integer not null,
        prescription_id integer generated by default as identity,
        uploaded_at timestamp(6) not null,
        prescription_image_url varchar(255),
        status varchar(255),
        primary key (prescription_id)
    );

    create table seller_rating (
        buyer_id integer,
        rating integer,
        rating_id integer generated by default as identity,
        seller_id integer,
        created_at timestamp(6),
        comment varchar(255),
        primary key (rating_id)
    );

    create table user_address (
        user_address_id integer generated by default as identity,
        user_id integer,
        apartment_number varchar(255),
        city varchar(255),
        country varchar(255),
        postal_code varchar(255),
        street varchar(255),
        primary key (user_address_id)
    );

    create table users (
        user_id integer generated by default as identity,
        created_at timestamp(6),
        email varchar(255) not null unique,
        name varchar(255),
        phone varchar(255),
        role varchar(255) not null check ((role in ('CUSTOMER','PHARMACY_OWNER','ADMIN'))),
        primary key (user_id)
    );

